/* =========================================================
   清除重複股票
========================================================= */

const STOCK_MAP =
new Map();


for(
  const [
    symbol,
    name,
    market
  ]
  of STOCKS
){

  if(
    !STOCK_MAP.has(symbol)
  ){

    STOCK_MAP.set(
      symbol,
      {
        symbol,
        name,
        market
      }
    );

  }

}


const STOCK_LIST =
[...STOCK_MAP.values()];


/* =========================================================
   API
========================================================= */

module.exports =
async function handler(req,res){

  res.setHeader(
    "Access-Control-Allow-Origin",
    "*"
  );

  res.setHeader(
    "Access-Control-Allow-Methods",
    "GET, OPTIONS"
  );

  res.setHeader(
    "Access-Control-Allow-Headers",
    "Content-Type"
  );

  res.setHeader(
    "Cache-Control",
    "no-store, no-cache, must-revalidate"
  );


  if(
    req.method==="OPTIONS"
  ){

    return res
      .status(200)
      .end();

  }


  try{

    const raw =
      String(
        req.query.q || ""
      ).trim();


    if(!raw){

      return res
        .status(200)
        .json({

          ok:true,

          items:[]

        });

    }


    const q =
      normalize(raw);


    const isNumber =
      /^\d+$/.test(q);


    let results =
      STOCK_LIST
      .map(
        stock=>{

          const symbol =
            normalize(
              stock.symbol
            );

          const name =
            normalize(
              stock.name
            );


          let score = 0;


          /*
            =========================
            股票代號搜尋
            =========================
          */

          if(isNumber){

            /*
              2330
            */

            if(
              symbol===q
            ){

              score=10000;

            }

            /*
              23
              233
            */

            else if(
              symbol.startsWith(q)
            ){

              score=9000;

            }

            /*
              330
            */

            else if(
              symbol.includes(q)
            ){

              score=8000;

            }

          }


          /*
            =========================
            中文名稱搜尋
            =========================
          */

          else{

            /*
              台積電
            */

            if(
              name===q
            ){

              score=10000;

            }


            /*
              台積
              聯發
              長榮
            */

            else if(
              name.startsWith(q)
            ){

              score=9000;

            }


            /*
              積電
              發科
              榮航
            */

            else if(
              name.includes(q)
            ){

              score=8000;

            }


            /*
              字元順序模糊比對

              例如：
              台電
              可以找到名稱中依序出現
              台...電 的股票
            */

            else if(
              fuzzyContains(
                name,
                q
              )
            ){

              score=6000;

            }

          }


          /*
            名稱越接近輸入長度，
            排名稍微提高。
          */

          if(score>0){

            score -=
              Math.abs(
                name.length -
                q.length
              );

          }


          return {

            ...stock,

            score

          };

        }
      )

      .filter(
        stock=>
          stock.score>0
      )

      .sort(
        (a,b)=>{

          if(
            b.score!==a.score
          ){

            return (
              b.score -
              a.score
            );

          }


          return (
            a.symbol.localeCompare(
              b.symbol
            )
          );

        }
      )

      .slice(
        0,
        20
      )

      .map(
        stock=>({

          symbol:
            stock.symbol,

          name:
            stock.name,

          market:
            stock.market

        })
      );


    return res
      .status(200)
      .json({

        ok:true,

        query:raw,

        count:
          results.length,

        items:
          results

      });


  }catch(error){

    console.error(
      "search error:",
      error
    );


    return res
      .status(500)
      .json({

        ok:false,

        error:
          error?.message ||
          "搜尋失敗"

      });

  }

};


/* =========================================================
   Normalize
========================================================= */

function normalize(value){

  return String(
    value || ""
  )

  .toLowerCase()

  .trim()

  .replace(
    /\s+/g,
    ""
  )

  .replace(
    /台灣/g,
    "臺灣"
  )

  .replace(
    /[\-_.()（）]/g,
    ""
  );

}


/* =========================================================
   模糊中文比對
========================================================= */

function fuzzyContains(
  text,
  query
){

  if(
    !text ||
    !query
  ){

    return false;

  }


  let index=0;


  for(
    const char of text
  ){

    if(
      char===
      query[index]
    ){

      index++;

    }


    if(
      index===
      query.length
    ){

      return true;

    }

  }


  return false;

}
